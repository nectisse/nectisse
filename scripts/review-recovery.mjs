import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtemp, mkdir, writeFile, rename, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import electron from 'electron';
import { _electron } from 'playwright-core';
const root=fileURLToPath(new URL('..',import.meta.url));
const appPath=process.argv[2]?resolve(process.argv[2]):undefined;
const profile=await mkdtemp(join(tmpdir(),'nectisse-workspace-review-recovery-'));
const output=join(root,'.test-output/recovery');
let app;
try {
 await mkdir(output,{recursive:true});
 execFileSync(process.execPath,['--import','tsx',join(root,'scripts/seed-workspace-fixtures.ts'),profile],{cwd:root,stdio:'pipe'});
 const cache=join(profile,'cache/subscription-covers');
 await rename(cache,`${cache}.fixture-backup`);await writeFile(cache,'Temporary startup obstruction');
 app=await _electron.launch({executablePath:appPath?join(appPath,'Contents/MacOS/Nectisse'):electron,args:[...(appPath?[]:[root]),`--user-data-dir=${profile}`],cwd:profile});
 const page=await app.firstWindow();await page.locator('[data-testid="runtime-status"][data-phase="ready"]').waitFor();
 await page.locator('.environment-alert').waitFor({timeout:5000});
 console.log(JSON.stringify({phase:'before-retry',notice:await page.evaluate(()=>window.nectisse.subscriptions.getState().then(state=>state.notice,()=> 'SUBSCRIPTIONS_UNAVAILABLE'))}));
 const pid=app.process().pid;
 await rm(cache);await rename(`${cache}.fixture-backup`,cache);
 await page.getByRole('button',{name:'重新检查',exact:true}).click();
 await page.waitForFunction(()=>!document.querySelector('.environment-alert'),{},{timeout:5000});
 assert.equal(app.process().pid,pid,'恢复必须在同一个进程内完成');
 const reply=await page.evaluate(async()=>{const state=await window.nectisse.subscriptions.getState();return window.nectisse.subscriptions.command({action:'preferences',value:{...state.preferences,theme:'night'}});});
 assert.equal(reply.ok,true,'初始化失败恢复后必须可以保存设置');
 assert.equal((await page.evaluate(()=>window.nectisse.subscriptions.getState())).subscriptions.length,2,'恢复保留既有订阅');

 // A transient database-open failure must leave the recovery IPC registered.
 await app.close();app=undefined;
 const database=join(profile,'nectisse.sqlite');
 await rename(database,`${database}.fixture-backup`);await mkdir(database);
 app=await _electron.launch({executablePath:appPath?join(appPath,'Contents/MacOS/Nectisse'):electron,args:[...(appPath?[]:[root]),`--user-data-dir=${profile}`],cwd:profile});
 let current=await app.firstWindow();await current.locator('[data-testid="runtime-status"][data-phase="ready"]').waitFor();
 await current.locator('.environment-alert').waitFor({timeout:6000});const databasePid=app.process().pid;
 await rm(database,{recursive:true});await rename(`${database}.fixture-backup`,database);
 await current.getByRole('button',{name:'重新检查',exact:true}).click();
 await current.waitForFunction(()=>document.querySelectorAll('.sidebar-author').length===2&&!document.querySelector('.environment-alert'),{},{timeout:6000});
 assert.equal(app.process().pid,databasePid);
 assert.equal((await current.evaluate(()=>window.nectisse.subscriptions.getState())).preferences.theme,'night');
 assert.equal((await current.evaluate(()=>window.nectisse.metadata.getState())).tasks.length,1);
 // A rejected metadata-initialization promise must also be replaceable.
 await app.close();app=undefined;
 const metadata=join(profile,'metadata');await rename(metadata,`${metadata}.fixture-backup`);await writeFile(metadata,'Temporary startup obstruction');
 app=await _electron.launch({executablePath:appPath?join(appPath,'Contents/MacOS/Nectisse'):electron,args:[...(appPath?[]:[root]),`--user-data-dir=${profile}`],cwd:profile});
 current=await app.firstWindow();await current.getByRole('button',{name:'重新检查查询服务',exact:true}).waitFor({timeout:6000});
 const metadataPid=app.process().pid;await rm(metadata);await rename(`${metadata}.fixture-backup`,metadata);
 await current.getByRole('button',{name:'重新检查查询服务',exact:true}).click();
 await current.getByRole('button',{name:'重新检查查询服务',exact:true}).waitFor({state:'hidden',timeout:6000});
 assert.equal(app.process().pid,metadataPid);
 assert.equal((await current.evaluate(()=>window.nectisse.metadata.getState())).tasks.length,1);
 const before=await current.evaluate(()=>window.nectisse.subscriptions.getState());
 const retries=await current.evaluate(()=>Promise.all(Array.from({length:5},()=>window.nectisse.subscriptions.retry())));
 assert.ok(retries.every(state=>state.subscriptions.length===2));
 assert.deepEqual(retries.at(-1).tasks,before.tasks,'重复恢复不能复活或重建既有任务');
 await current.screenshot({path:join(output,'recovered-without-restart.png')});
 console.log(JSON.stringify({checks:['cache-startup-failure-reproduced','retry-recovers-in-same-process','preferences-writable-after-retry','saved-subscriptions-preserved','database-open-recovery-ipc-available','metadata-initialization-recovery','healthy-retries-do-not-recreate-tasks']},null,2));
}finally{await app?.close().catch(()=>{});await rm(profile,{recursive:true,force:true});}
